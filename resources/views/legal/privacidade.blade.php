    <p>Este Aviso de Privacidade descreve como a <strong>INAMEX</strong> trata os dados pessoais
        — inclusive dados pessoais sensíveis de saúde — no sistema interno de controle clínico
        utilizado por sua equipe, em conformidade com a Lei nº 13.709/2018 (Lei Geral de Proteção
        de Dados — LGPD).</p>

    <h2>1. Controladora</h2>
    <p>A controladora dos dados é a <strong>INAMEX</strong>, instituição responsável pela assistência
        à saúde das pacientes internadas, que define as finalidades e os meios do tratamento.</p>

    <h2>2. Finalidade do tratamento</h2>
    <p>Os dados são tratados exclusivamente para a <strong>prestação de assistência à saúde</strong>
        das pacientes: registro clínico, acompanhamento de prontuário, prescrição e administração de
        medicação, e geração de relatórios assistenciais. Os dados não são utilizados para
        finalidades comerciais, de marketing ou compartilhados com terceiros fora desta finalidade.</p>

    <h2>3. Base legal</h2>
    <p>O tratamento de dados pessoais sensíveis de saúde fundamenta-se no
        <strong>art. 11, inciso II, alínea "f"</strong> da LGPD — tratamento indispensável para a
        <em>tutela da saúde</em>, em procedimento realizado por profissionais de saúde ou por serviços
        de saúde. Aplica-se ainda, no que couber, a proteção reforçada dos arts. 11 e 46 da LGPD
        quanto à segurança da informação.</p>

    <h2>4. Dados tratados</h2>
    <ul>
        <li>Dados de identificação da paciente (nome, número de prontuário, quarto e fotografia);</li>
        <li>Dados clínicos: ficha médica, laudos, diagnósticos, medicamentos de uso crônico;</li>
        <li>Prontuário diário e histórico de evolução;</li>
        <li>Prescrições e registros de administração de medicação;</li>
        <li>Dados dos profissionais usuários do sistema (nome, cargo, turno e trilha de acessos).</li>
    </ul>

    <h2>5. Quem acessa, por cargo</h2>
    <p>O acesso é restrito à equipe autorizada, segundo o cargo e a necessidade assistencial:</p>
    <ul>
        <li><strong>Médico</strong> e <strong>diretor</strong>: leitura clínica e geração de relatórios;</li>
        <li><strong>Chefe de enfermagem</strong>: gestão de pacientes, fichas e registros;</li>
        <li><strong>Enfermeiro</strong> e <strong>técnico</strong>: registro operacional de medicação;</li>
        <li><strong>Administrador</strong>: gestão de usuários, auditoria e configuração.</li>
    </ul>
    <p>Todos os acessos e alterações são registrados em trilha de auditoria.</p>

    <h2>6. Guarda e prazo de retenção</h2>
    <p>O prontuário é guardado pelo prazo e na forma exigidos pela legislação sanitária aplicável,
        em especial a <strong>Lei nº 13.787/2018</strong> (digitalização e guarda de prontuários) e a
        <strong>Resolução CFM nº 1.821/2007</strong>, que estabelece o prazo mínimo de guarda de
        20 (vinte) anos a partir do último registro, podendo o documento ser eliminado ou
        permanentemente arquivado após esse prazo.</p>

    <h2>7. Direitos do titular</h2>
    <p>Nos termos do <strong>art. 18 da LGPD</strong>, o titular dos dados pode solicitar, entre outros:
        confirmação da existência de tratamento; acesso aos dados; correção de dados incompletos,
        inexatos ou desatualizados; anonimização, bloqueio ou eliminação de dados tratados em
        desconformidade; portabilidade; e informação sobre o compartilhamento. O exercício de certos
        direitos observa os limites legais de guarda do prontuário.</p>

